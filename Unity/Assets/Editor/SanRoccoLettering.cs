        public static void Paint(Transform p,string text,float maxWidth,float height,Material paint)
        {
            var v=new List<Vector3>();var t=new List<int>();text=text.ToUpperInvariant();
            float unit=Mathf.Min(height/7,maxWidth/Mathf.Max(1,text.Length*6-1)),left=-(text.Length*6-1)*unit/2;
            for(int k=0;k<text.Length;k++) {
                char c=text[k];int index=c>='A'&&c<='Z'?c-'A':c>='0'&&c<='9'?26+c-'0':-1;
                string mask=index>=0?Glyphs[index]:c=='-'?"00000/00000/00000/11111/00000/00000/00000":c=='/'?"00001/00001/00010/00100/01000/10000/10000":c==':'?"00000/00100/00100/00000/00100/00100/00000":"00000/00000/00000/00000/00000/00000/00000";
                var rows=mask.Split('/');
                for(int y=0;y<7;y++) for(int x=0;x<5;x++) if(rows[y][x]=='1') {
                    int end=x;while(end+1<5 && rows[y][end+1]=='1') end++;
                    float a=left+(k*6+x)*unit,b=left+(k*6+end+1)*unit,top=(3.5f-y)*unit+Mathf.Sin(k*2.3f)*unit*.035f,bottom=top-unit;
                    int n=v.Count;v.AddRange(new[]{new Vector3(a,bottom,0),new Vector3(a,top,0),new Vector3(b,top,0),new Vector3(b,bottom,0)});
                    t.AddRange(new[]{n,n+1,n+2,n,n+2,n+3});x=end;
                }
            }
            if(v.Count>0) Mesh(p,"lettere_dipinte",v.ToArray(),t.ToArray(),paint,false);
        }
    }
